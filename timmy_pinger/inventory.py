"""The host list files scanT writes and rescans.

A new scan writes one [group] per group with its subnets above it as "# 10.0.10.0/24: ..."
lines - a rescan reads them back to know what to scan. A rescan only adds: the new hosts go
to the end of their group, nothing else in the file changes (DECISIONS.md "A rescan only adds")."""

from __future__ import annotations

import ipaddress
import os
import re
import shutil
from datetime import datetime

from .hostlist import INLINE_COMMENT, is_ipv4, read_host_list

IPV4 = r"\d{1,3}(?:\.\d{1,3}){3}"
SUBNET_LINE = re.compile(rf"^#\s*({IPV4}/\d{{1,2}})\s*:")  # "# 10.0.10.0/24: 11 of 254 addresses answered"
COMMENTED_OUT_HOST = re.compile(rf"^#\s*({IPV4})(?=[\s,]|$)")  # "# 10.0.10.5 old-pc": taken out on purpose


def ip_order(target: str):
    """Sort key: IPs in numeric order, then DNS names."""
    return (0, ipaddress.IPv4Address(target)) if is_ipv4(target) else (1, target)


def is_group_line(line: str) -> bool:
    line = INLINE_COMMENT.sub("", line.strip()).strip()
    return line.startswith("[") and line.endswith("]")


def new_host_list(groups: dict[str, list[tuple[str, int, int]]], hosts: dict[str, list[str]], scanned: int,
                  passes: int, version: str) -> str:
    """groups: group -> [(subnet, answered, scanned)]; hosts: group -> its IPs."""
    answered = sum(len(ips) for ips in hosts.values())
    lines = [f"# generated by scanT {version} on {datetime.now():%Y-%m-%d %H:%M}, ICMP sweep, {passes} passes",
             f"# {answered} hosts answered out of {scanned} scanned addresses", ""]
    for group, subnets in groups.items():
        lines += [f"# {subnet}: {found} of {size} addresses answered" for subnet, found, size in subnets]
        lines.append(f"[{group}]")
        lines += sorted(hosts.get(group, []), key=ip_order)
        lines.append("")
    return "\n".join(lines)


class HostListFile:
    """An existing host list, for a rescan."""

    def __init__(self, path: str):
        with open(path, encoding="utf-8-sig") as fh:
            self.lines = fh.read().splitlines()
        self.subnets: list[tuple[str, str | None]] = []  # (subnet, its group) from the "# CIDR:" lines
        self.commented_out: set[str] = set()
        self.known: dict[str, tuple[str, str | None]] = {}  # target -> (label or "", group)
        waiting: list[str] = []  # subnet lines not yet followed by a [group] or a host line
        group = None
        for raw in self.lines:
            line = raw.strip()
            if match := SUBNET_LINE.match(line):
                waiting.append(match.group(1))
                continue
            if line.startswith("#"):
                if match := COMMENTED_OUT_HOST.match(line):
                    self.commented_out.add(match.group(1))
                continue
            content = INLINE_COMMENT.sub("", line).strip()
            if not content:
                continue
            if is_group_line(content):
                group = content[1:-1].strip() or None
            self.subnets += [(subnet, group) for subnet in waiting]  # above a [group], or above its host lines
            waiting = []
        self.subnets += [(subnet, group) for subnet in waiting]
        for entry in read_host_list(path):
            self.known.setdefault(entry.target, (entry.label if entry.label != entry.target else "", entry.group))
        self.commented_out -= set(self.known)

    def with_new_hosts(self, new_hosts: dict[str, list[str]], new_subnets: dict[str, list[str]]) -> str:
        """The file with the new hosts added at the end of their group (a group that isn't there
        yet is added at the end of the file). new_subnets: "# CIDR:" lines to add above a group,
        for subnets that came from -f, so the next rescan finds them by itself."""
        lines = list(self.lines)
        today = f"{datetime.now():%Y-%m-%d}"
        for group in dict.fromkeys([*new_hosts, *new_subnets]):
            host_lines = [f"{ip:<16} # new in rescan {today}" for ip in sorted(new_hosts.get(group, []), key=ip_order)]
            subnet_lines = [f"# {subnet}: subnet for scanT --rescan (added {today})"
                            for subnet in new_subnets.get(group, [])]
            start = next((i for i, line in enumerate(lines) if is_group_line(line)
                          and INLINE_COMMENT.sub("", line.strip()).strip()[1:-1].strip() == group), None)
            if start is None:
                if lines and lines[-1].strip():
                    lines.append("")
                lines += [*subnet_lines, f"[{group}]", *host_lines, ""]
                continue
            end = next((i for i in range(start + 1, len(lines)) if is_group_line(lines[i])), len(lines))
            # after the group's last host line - the comments before the next group belong to that one
            last_host = max((i for i in range(start, end) if lines[i].strip() and not lines[i].strip().startswith("#")),
                            default=start)
            lines[last_host + 1:last_host + 1] = host_lines
            lines[start:start] = subnet_lines
        return "\n".join(lines) + "\n"


def cannot_write(path: str) -> str | None:
    """Why path can't be written, or None - checked before scanning, so no scan is lost to a typo."""
    folder = os.path.dirname(os.path.abspath(path))
    if not os.path.isdir(folder):
        return f"folder {folder} does not exist"
    if not os.access(folder, os.W_OK):
        return f"no permission to write in {folder}"
    if os.path.exists(path) and not os.access(path, os.W_OK):
        return f"no permission to write {path}"
    return None


def write_file(path: str, text: str):
    """Atomic write (temp file + rename); an existing file is kept as <path>.bak first."""
    temp = path + ".tmp"
    with open(temp, "w", encoding="utf-8") as fh:
        fh.write(text)
    if os.path.exists(path):
        shutil.copy2(path, path + ".bak")
    os.replace(temp, path)
